const tour: Lesson[] = []
for (let i = 0; i < 64; i += 6) {
  const day = 51 + i / 6
  const group = HEXAGRAMS.slice(i, i + 6)
  const screens: Screen[] = [
    T('今天读这几卦', group.map((h) => `第${h.n}卦 **${h.name}**（${h.fullName}）：${h.gist}`).join('\n')),
    ...group.map((h) => ({ t: 'hex', title: `${h.n}. ${h.fullName}`, n: h.n }) as Screen),
  ]
  const quiz: Quiz[] = group.slice(0, 4).map((h, k) => {
    const others = HEXAGRAMS.filter((x) => x.n !== h.n)
    const pick = [others[(h.n * 7 + k) % 63], others[(h.n * 13 + 5) % 63]].filter((x, j, arr) => arr.indexOf(x) === j)
    const opts = [h.fullName, ...pick.map((x) => x.fullName)]
    const rot = h.n % opts.length
    const rotated = [...opts.slice(rot), ...opts.slice(0, rot)]
    return Q(`第 ${h.n} 卦「${h.name}」的全名是？`, rotated, rotated.indexOf(h.fullName), `上${h.upper.name}（${h.upper.nature}）下${h.lower.name}（${h.lower.nature}），读作${h.fullName}。`)
  })
  const last = group[group.length - 1]
  quiz.push(Q(`「${last.name}」卦的大意是？`, [last.gist, HEXAGRAMS[(last.n + 20) % 64].gist], 0, `${last.name}：${last.gist}`))
  tour.push(L(day, 'u4', `巡读：${group.map((h) => h.name).join('、')}`, `读第 ${group[0].n}～${group[group.length - 1].n} 卦`, screens, quiz, 15))
}

